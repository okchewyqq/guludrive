export type MessageKey = keyof typeof zh
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const message: string = (messageLanguage.value === 'zh' ? zh : en)[key]
  return message.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? '{' + name + '}'),
  )
}
export function formatSize(size: number): string {
  if (!Number.isFinite(size) || size < 0) return '—'
  if (size < 1024) return t('bytesValue', { count: size })
  const units = ['KB', 'MB', 'GB', 'TB', 'PB', 'EB']
  let value = size / 1024
  for (const unit of units) {
    if (value < 1024 || unit === 'EB')
      return new Intl.NumberFormat(messageLanguage.value === 'zh' ? 'zh-CN' : 'en', {
        minimumFractionDigits: 1,
        maximumFractionDigits: 1,
      }).format(value) + ' ' + unit
    value /= 1024
  }
  return '—'
}
// Mirrors ui/i18n.Modified: "2006年01月02日 15:04" or "02 Jan 2006 · 15:04" in local time.
export function formatDate(value: string): string {
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return '—'
  const pad = (n: number) => String(n).padStart(2, '0')
  const time = pad(date.getHours()) + ':' + pad(date.getMinutes())
  if (messageLanguage.value === 'zh') {
    return date.getFullYear() + '年' + pad(date.getMonth() + 1) + '月' + pad(date.getDate()) + '日 ' + time
  }
  const month = new Intl.DateTimeFormat('en-GB', { month: 'short' }).format(date)
  return pad(date.getDate()) + ' ' + month + ' ' + date.getFullYear() + ' · ' + time
}
// Mirrors ui/localization.go kind(): bucket, folder, content type, or "EXT file".
export function entryKind(entry: { isDir: boolean; path: string; name: string; contentType: string }): string {
  if (entry.isDir) {
    const depth = entry.path.replace(/^\/+|\/+$/g, '')
    return depth.includes('/') ? t('folder') : t('typeBucket')
  }
  if (entry.contentType && entry.contentType !== 'application/octet-stream') return entry.contentType
  const dot = entry.name.lastIndexOf('.')
  const ext = dot > 0 ? entry.name.slice(dot + 1) : ''
  return ext ? t('extFile', { ext: ext.toUpperCase() }) : t('file')
}
